/**
 * Playwright test scaffolding templates for Tizen web apps.
 *
 * Pure string renderers — kept as a lib module (not an asset file) so esbuild
 * inlines them into the tizen-cli bundle and the unbundled plugin-cache layout
 * needs no extra copy step. The plugin itself must NEVER require('playwright');
 * the generated test file resolves it from the TEST PROJECT's node_modules.
 *
 * The template encodes the Tizen-specific rules a generic Playwright test
 * would get wrong:
 *  - attach-only: the Tizen web runtime owns the single page. Never
 *    newPage()/goto() — navigating kills the app UI.
 *  - console/pageerror listeners registered BEFORE any interaction, so logs
 *    emitted by the assertions are not missed.
 *  - assertions that really fail the process (non-zero exit code) — unlike
 *    console.assert, which only prints to stderr.
 *  - endpoint from TIZEN_CDP_ENDPOINT env (set by the runner) instead of a
 *    hardcoded port.
 *  - machine-readable "TEST_RESULT: pass|fail total=N failed=M errors=K"
 *    marker on the last line, parsed by parseTestSummary() in
 *    playwright-test.js. Page runtime errors (pageerror) are counted in
 *    errors=K, separately from assertion failures, so the marker never
 *    reports failed > total — either kind still fails the run.
 */

/**
 * Render the scaffolded test file content.
 *
 * @param {object} [opts]
 * @param {string} [opts.appId] - baked-in fallback app ID (env still wins)
 * @param {number|string} [opts.port=9222] - fallback CDP port for standalone runs
 * @returns {string} tizen-playwright.test.js content
 */
function renderTestTemplate(opts = {}) {
  const appId = opts.appId || "your.AppId";
  const port = opts.port || 9222;
  return `// tizen-playwright.test.js — generated by the tizen-playwright-test skill
//
// Runs against an ALREADY-LAUNCHED Tizen web app over CDP. The runner
// (playwright-test-cli.js) sets up the RWI/CDP port forward and passes the
// endpoint via TIZEN_CDP_ENDPOINT; running this file standalone also works
// while the forward from a previous setup is still alive.
//
// ATTACH-ONLY: the Tizen web runtime owns the single page. Never call
// page.goto() or context.newPage() — navigating kills the app UI.

const { chromium } = require('playwright');

const CDP_ENDPOINT = process.env.TIZEN_CDP_ENDPOINT || 'http://127.0.0.1:${port}';
const APP_ID = process.env.TIZEN_APP_ID || '${appId}';

let total = 0;
let failed = 0;
let pageErrors = 0; // page runtime errors — counted separately from assertions

// Assertion that REALLY fails the process (console.assert never sets the exit code).
async function expect(name, fn) {
  total++;
  try {
    const ok = await fn();
    if (!ok) throw new Error('assertion returned false');
    console.log(\`PASS \${name}\`);
  } catch (e) {
    failed++;
    console.error(\`FAIL \${name} — \${e.message}\`);
  }
}

(async () => {
  let browser = null;
  let page = null;
  try {
    browser = await chromium.connectOverCDP(CDP_ENDPOINT);
    const context = browser.contexts()[0];
    page = context && context.pages()[0];
    if (!page) throw new Error(\`No page attached — is \${APP_ID} running in debug mode?\`);

    // Register listeners EARLY, before any interaction, so nothing is missed.
    page.on('console', (msg) => console.log(\`[app console:\${msg.type()}] \${msg.text()}\`));
    page.on('pageerror', (err) => {
      pageErrors++;
      console.error(\`[app pageerror] \${err.message}\`);
    });

    // ── Your tests ──────────────────────────────────────────────────────────
    await expect('app page has a body', async () =>
      (await page.locator('body').count()) === 1);
    await expect('app title is not empty', async () =>
      (await page.title()) !== '');
    // TODO: add app-specific assertions, e.g. for the BasicUI template:
    // await page.locator('#main').click();
    // await expect('text toggled to Tizen', async () =>
    //   (await page.locator('#content-text').textContent()) === 'Tizen');
    // ────────────────────────────────────────────────────────────────────────
  } catch (e) {
    failed++;
    if (total === 0) total = 1;
    console.error(\`TEST ERROR: \${e.message}\`);
    if (/ECONNREFUSED/.test(String(e.message))) {
      console.error('CDP endpoint unreachable — re-run the tizen-webapp-debug setup '
        + '(restarting the app invalidates the RWI port).');
    }
  } finally {
    const ok = failed === 0 && pageErrors === 0;
    if (page && !ok) {
      try {
        await page.screenshot({ path: 'test-failure.png' });
        console.error('Saved screenshot: test-failure.png');
      } catch (e) { /* page may be gone */ }
    }
    if (browser) {
      try { await browser.close(); } catch (e) { /* already closed */ }
    }
    console.log(\`TEST_RESULT: \${ok ? 'pass' : 'fail'} total=\${total} failed=\${failed} errors=\${pageErrors}\`);
    process.exit(ok ? 0 : 1);
  }
})();
`;
}

/**
 * Render a minimal package.json for a fresh test project directory.
 * Only written when the directory has no package.json — an existing one is
 * never touched (the caller adds a warning instead).
 *
 * @param {object} [opts]
 * @param {string} [opts.name='tizen-playwright-tests']
 * @returns {string} package.json content
 */
function renderPackageJson(opts = {}) {
  return (
    JSON.stringify(
      {
        name: opts.name || "tizen-playwright-tests",
        private: true,
        type: "commonjs",
        dependencies: {
          playwright: "^1.62.1",
        },
      },
      null,
      2,
    ) + "\n"
  );
}

module.exports = { renderTestTemplate, renderPackageJson };
